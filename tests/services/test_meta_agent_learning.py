"""Tests for auto-playbook generation and confidence tracking wired into SorenMetaAgent."""

from __future__ import annotations

from unittest.mock import AsyncMock, MagicMock, patch

import pytest

from soren.models.session import TaskResult
from soren.models.site_playbook import ExecutionFlow, FlowPlaybook, PlaybookStep, SiteFlows, SitePlaybook
from tests.services.conftest import build_meta_agent


def _make_flow_playbook(verified_by: str | None = "auto") -> FlowPlaybook:
    return FlowPlaybook(
        verified_by=verified_by,
        confidence=0.5,
        steps=[PlaybookStep(seq=1, instruction="Click submit", expected_after="Done")],
    )


class TestSuccessfulExecutionTriggersAutoPlaybook:
    """auto_generate_site_playbook is called after successful execution."""

    @pytest.mark.asyncio
    async def test_successful_execution_triggers_auto_playbook(self) -> None:
        agent = build_meta_agent()
        mock_auto_gen = AsyncMock(return_value=_make_flow_playbook())

        with patch(
            "soren.services.auto_playbook.auto_generate_site_playbook",
            mock_auto_gen,
        ):
            report = await agent.run_cycle()

        assert report.task_result is not None
        assert report.task_result.success is True
        mock_auto_gen.assert_called_once()
        call_kwargs = mock_auto_gen.call_args
        assert call_kwargs[1]["source_name"] == "TestSource"


class TestAutoGeneratedPlaybookSavedViaSaveFlow:
    """save_flow is called with the auto-generated playbook."""

    @pytest.mark.asyncio
    async def test_auto_generated_playbook_saved_via_save_flow(self) -> None:
        playbook_service = MagicMock()
        playbook_service.write_back = AsyncMock(return_value=MagicMock(dry_run=False, preview=None))
        playbook_service.load_site.return_value = None
        playbook_service.save_flow.return_value = MagicMock()
        playbook_service.update_confidence = MagicMock()

        auto_flow = _make_flow_playbook()
        agent = build_meta_agent(playbook_service=playbook_service)

        with patch(
            "soren.services.auto_playbook.auto_generate_site_playbook",
            AsyncMock(return_value=auto_flow),
        ):
            await agent.run_cycle()

        playbook_service.save_flow.assert_called_once_with("TestSource", "execution", auto_flow, task_type="survey")


class TestHumanTrainedPlaybooksNotOverwritten:
    """save_flow is NOT called when existing flow has verified_by='human'."""

    @pytest.mark.asyncio
    async def test_human_trained_playbooks_not_overwritten(self) -> None:
        human_flow = ExecutionFlow(
            verified_by="human",
            confidence=0.9,
            steps=[PlaybookStep(seq=1, instruction="Human step", expected_after="Done")],
        )
        existing_site = SitePlaybook(
            source_name="TestSource",
            source_url="https://example.com",
            flows=SiteFlows(execution={"survey": human_flow}),
        )

        playbook_service = MagicMock()
        playbook_service.write_back = AsyncMock(return_value=MagicMock(dry_run=False, preview=None))
        playbook_service.load_site.return_value = existing_site
        playbook_service.save_flow.return_value = MagicMock()
        playbook_service.update_confidence = MagicMock()

        agent = build_meta_agent(playbook_service=playbook_service)

        with patch(
            "soren.services.auto_playbook.auto_generate_site_playbook",
            AsyncMock(return_value=_make_flow_playbook()),
        ):
            await agent.run_cycle()

        playbook_service.save_flow.assert_not_called()


